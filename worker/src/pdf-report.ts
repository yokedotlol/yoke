// ─── Text Helpers ────────────────────────────────────────────────

function textWidth(font: PDFFont, text: string, size: number): number {
  try {
    return font.widthOfTextAtSize(text, size);
  } catch {
    let w = 0;
    for (const ch of text) {
      try {
        w += font.widthOfTextAtSize(ch, size);
      } catch {
        w += size * 0.5;
      }
    }
    return w;
  }
}

function truncateText(font: PDFFont, text: string, size: number, maxWidth: number): string {
  if (!text) return "";
  const str = String(text);
  if (textWidth(font, str, size) <= maxWidth) return str;
  let truncated = str;
  while (truncated.length > 1 && textWidth(font, `${truncated}...`, size) > maxWidth) {
    truncated = truncated.slice(0, -1);
  }
  return `${truncated}...`;
}

function wrapText(font: PDFFont, text: string, size: number, maxWidth: number): string[] {
  if (!text) return [""];
  const str = String(text);
  const words = str.split(/\s+/);
  const lines: string[] = [];
  let currentLine = "";
  for (const word of words) {
    if (textWidth(font, word, size) > maxWidth) {
      if (currentLine) {
        lines.push(currentLine);
        currentLine = "";
      }
      let remaining = word;
      while (remaining.length > 0) {
        let fit = "";
        for (let i = 1; i <= remaining.length; i++) {
          const sub = remaining.slice(0, i);
          if (textWidth(font, sub, size) > maxWidth) break;
          fit = sub;
        }
        if (!fit) fit = remaining.slice(0, 1);
        lines.push(fit);
        remaining = remaining.slice(fit.length);
      }
      continue;
    }
    const testLine = currentLine ? `${currentLine} ${word}` : word;
    if (textWidth(font, testLine, size) <= maxWidth) {
      currentLine = testLine;
    } else {
      if (currentLine) lines.push(currentLine);
      currentLine = word;
    }
  }
  if (currentLine) lines.push(currentLine);
  return lines.length ? lines : [""];
}

function safeText(text: string | number | null | undefined): string {
  if (!text && text !== 0) return "";
  // biome-ignore lint/suspicious/noControlCharactersInRegex: intentionally stripping control characters
  return String(text).replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "");
}

// ─── Drawing Helpers ─────────────────────────────────────────────

function drawText(
  page: PDFPage,
  text: string | number | null | undefined,
  x: number,
  y: number,
  font: PDFFont,
  size: number,
  color: Color,
  options: { maxWidth?: number; wrap?: boolean } = {},
): void {
  const str = safeText(text);
  if (!str) return;
  const maxWidth = options.maxWidth || CONTENT_W - (x - MARGIN);
  const display = options.wrap ? str : truncateText(font, str, size, maxWidth);
  try {
    page.drawText(display, { x, y, size, font, color });
  } catch {
    const safe = display.replace(/[^\x20-\x7E]/g, "?");
    page.drawText(safe, { x, y, size, font, color });
  }
}

function drawRect(page: PDFPage, x: number, y: number, w: number, h: number, options: DrawRectOpts = {}): void {
  page.drawRectangle({
    x,
    y,
    width: w,
    height: h,
    color: options.fill,
    borderColor: options.border,
    borderWidth: options.borderWidth || (options.border ? 1 : 0),
    opacity: options.opacity,
    borderOpacity: options.borderOpacity,
  });
}

function drawLine(page: PDFPage, x1: number, y1: number, x2: number, y2: number, color: Color, width = 1): void {
  page.drawLine({ start: { x: x1, y: y1 }, end: { x: x2, y: y2 }, color, thickness: width });
}

