// PAGE 5 — SCORE BREAKDOWN
// ═══════════════════════════════════════════════════════════════════

function buildPage5_ScoreBreakdown(doc: PDFDocument, fonts: Fonts, data: AnalysisData): PDFPage[] {
  const pages = [];
  let page = doc.addPage([PAGE_W, PAGE_H]);
  pages.push(page);
  drawPageHeader(page, fonts, "Score Breakdown");

  const ds = data.domain_score;
  const composite = ds.composite;
  const tier = ds.tier || tierFromScore(composite);
  const color = tierColor(tier);
  let y = CONTENT_TOP;

  // ── Section title ──
  drawRect(page, MARGIN - 8 - 3, y - 4, 3, 20, { fill: COLORS.accent });
  drawText(page, "SCORE BREAKDOWN", MARGIN, y, fonts.bold, 14, COLORS.accent);
  y -= 28;

  // ── Composite formula: SEC 85×.24 + SPD 88×.18 + ... = 89 ──
  const formulaParts = [];
  for (const axis of AXIS_ORDER) {
    const ax = ds.axes[axis];
    if (!ax) continue;
    const w = AXIS_WEIGHTS[axis];
    formulaParts.push(`${AXIS_ABBR[axis]} ${ax.score}×${w.toFixed(2)}`);
  }
  const formulaStr = `${formulaParts.join("  +  ")} = ${composite}`;

  // Draw formula in mono — may be long, so truncate if needed
  drawText(page, formulaStr, MARGIN, y, fonts.mono, 7.5, COLORS.text, { maxWidth: CONTENT_W });
  y -= 30;

  // ── Tier Progress Bar ──
  const barW = CONTENT_W;
  const barH = 16;
  const barY = y - barH;

  // Draw tier segments
  for (const td of TIER_DEFS) {
    const segX = MARGIN + (td.min / 100) * barW;
    const segW = ((td.max - td.min) / 100) * barW;
    drawRect(page, segX, barY, segW, barH, { fill: td.color, opacity: 0.15 });
    // Tier label inside segment
    const labelW = textWidth(fonts.regular, td.tier, 6.5);
    if (segW > labelW + 4) {
      drawText(page, td.tier, segX + (segW - labelW) / 2, barY + 5, fonts.regular, 6.5, td.color);
    }
  }
  drawRect(page, MARGIN, barY, barW, barH, { border: COLORS.border, borderWidth: 0.5 });

  // Score indicator — small triangle above
  const indicatorX = MARGIN + (composite / 100) * barW;
  // Draw a triangle pointing down
  const triSize = 4;
  const triTop = barY + barH + triSize + 1;
  page.drawSvgPath(`M 0,0 L ${triSize},-${triSize * 1.5} L ${-triSize},-${triSize * 1.5} Z`, {
    x: indicatorX,
    y: triTop,
    color: color,
  });
  // Score label above indicator — clear gap above triangle
  const scoreLabel = `${composite} · ${tier}`;
  const slW = textWidth(fonts.bold, scoreLabel, 8);
  const labelX = Math.max(MARGIN, Math.min(indicatorX - slW / 2, PAGE_W - MARGIN - slW));
  drawText(page, scoreLabel, labelX, triTop + 10, fonts.bold, 8, color);

  y = barY - 12;

  // ── Per-axis deduction breakdowns ──
  // Sort by composite impact (weight * deduction) — highest first
  const axisData = AXIS_ORDER.map((axis) => {
    const ax = ds.axes[axis];
    if (!ax) return null;
    const totalDeduction = 100 - ax.score;
    const compositeImpact = totalDeduction * (AXIS_WEIGHTS[axis] || 0);
    return { axis, score: ax.score, totalDeduction, compositeImpact, deductions: ax.deductions || [] };
  }).filter((x): x is NonNullable<typeof x> => x != null);

  axisData.sort((a, b) => b.compositeImpact - a.compositeImpact);

  for (const axInfo of axisData) {
    const axScore = axInfo.score;
    const axTier = tierFromScore(axScore);
    const axColor = tierColor(axTier);
    const axLabel = AXIS_LABELS[axInfo.axis];
    const axWeight = AXIS_WEIGHTS[axInfo.axis];

    // Check if we need a new page
    if (y < CONTENT_BOTTOM + 60) {
      page = doc.addPage([PAGE_W, PAGE_H]);
      pages.push(page);
      drawPageHeader(page, fonts, "Score Breakdown (continued)");
      y = CONTENT_TOP;
    }

    // Axis header line
    drawRect(page, MARGIN - 6 - 2, y - 2, 2, 12, { fill: axColor });
    drawText(page, `${axLabel}`, MARGIN, y, fonts.semibold, 10, COLORS.text);

    const deductionTotal = axInfo.totalDeduction;
    const metaText = `${axScore} · ${axTier}  |  ${Math.round(axWeight * 100)}% weight  |  -${deductionTotal.toFixed(1)} points`;
    const mtW = textWidth(fonts.regular, metaText, 8);
    drawText(page, metaText, PAGE_W - MARGIN - mtW, y + 1, fonts.regular, 8, axColor);
    y -= 18;

    // Collect signals from deductions
    const issues = []; // fixable: deduction > 0, not absent
    const opportunities = []; // absent + actionable
    const notAssessed = []; // absent + not actionable

    for (const ded of axInfo.deductions) {
      if (ded.signal === "_absent" && ded.absentSignals) {
        for (const abs of ded.absentSignals) {
          const item = {
            signal: abs.signal,
            label: abs.absentLabel || abs.label,
            deduction: abs.deduction || 0,
            weight: abs.weight || 1,
            effort: abs.effort,
            fixDescription: abs.fixDescription,
            actionable: abs.actionable !== false,
          };
          if (item.actionable) {
            opportunities.push(item);
          } else {
            notAssessed.push(item);
          }
        }
      } else if (ded.deduction > 0) {
        issues.push({
          signal: ded.signal,
          label: ded.label,
          deduction: ded.deduction,
          weight: ded.weight || 1,
          severity: ded.severity,
          effort: ded.effort,
          fixDescription: ded.fixDescription,
        });
      }
    }

    // Sort each group by deduction desc
    issues.sort((a, b) => b.deduction - a.deduction);
    opportunities.sort((a, b) => b.deduction - a.deduction);
    notAssessed.sort((a, b) => b.deduction - a.deduction);

    // Draw signal groups
    const groups = [
      { title: "Issues", items: issues, dotColor: COLORS.weak },
      { title: "Improvements", items: opportunities, dotColor: COLORS.moderate },
      { title: "Not Assessed", items: notAssessed, dotColor: COLORS.absent },
    ];

    for (const group of groups) {
      if (group.items.length === 0) continue;

      if (y < CONTENT_BOTTOM + 30) {
        page = doc.addPage([PAGE_W, PAGE_H]);
        pages.push(page);
        drawPageHeader(page, fonts, "Score Breakdown (continued)");
        y = CONTENT_TOP;
      }

      // Group label
      drawText(page, group.title, MARGIN + 12, y, fonts.medium, 8, COLORS.textSecondary);
      y -= 12;

      for (const item of group.items) {
        if (y < CONTENT_BOTTOM + 14) {
          page = doc.addPage([PAGE_W, PAGE_H]);
          pages.push(page);
          drawPageHeader(page, fonts, "Score Breakdown (continued)");
          y = CONTENT_TOP;
        }

        // Severity dot
        page.drawCircle({ x: MARGIN + 16, y: y - 2, size: 2.5, color: group.dotColor });

        // Label (truncated to fit)
        const label = safeText(item.label || item.signal);
        const deductStr = item.deduction > 0 ? `-${item.deduction.toFixed(1)}` : "0";
        const deductW = textWidth(fonts.mono, deductStr, 8);

        const labelMaxW = CONTENT_W - 32 - deductW - 12;
        drawText(page, label, MARGIN + 24, y - 4, fonts.regular, 8.5, COLORS.text, { maxWidth: labelMaxW });

        // Deduction amount (right-aligned, monospace)
        const dedX = PAGE_W - MARGIN - deductW;
        drawText(page, deductStr, dedX, y - 4, fonts.mono, 8, item.deduction > 0 ? COLORS.weak : COLORS.dim);

        y -= 14;
      }
      y -= 4;
    }

    // If no deductions at all
    if (issues.length === 0 && opportunities.length === 0 && notAssessed.length === 0) {
      drawText(page, "No deductions — perfect score in this axis.", MARGIN + 12, y, fonts.regular, 8.5, COLORS.good);
      y -= 14;
    }

    y -= 8; // Spacing between axes
  }

  return pages;
}

