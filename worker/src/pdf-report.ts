// ─── Main Export ─────────────────────────────────────────────────

export async function generatePdfReport(data: AnalysisData, fontData: PdfFontData): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.registerFontkit(fontkit);
  doc.setTitle(`Yoke Domain Intelligence Report — ${data.domain}`);
  doc.setAuthor(REPORT_CONFIG.footerUrl);
  doc.setSubject(`Domain analysis report for ${data.domain}`);
  doc.setCreationDate(new Date());

  // Load fonts from KV-sourced binary data
  const fonts: Fonts = {
    regular: await doc.embedFont(fontData.interRegular),
    medium: await doc.embedFont(fontData.interMedium),
    semibold: await doc.embedFont(fontData.interSemiBold),
    bold: await doc.embedFont(fontData.interBold),
    mono: await doc.embedFont(fontData.jetBrainsMono),
  };

  // Build pages
  const allPages: PDFPage[] = [];
  allPages.push(buildPage1(doc, fonts, data));
  allPages.push(buildPage2_Security(doc, fonts, data));
  allPages.push(buildPage3_SpeedFoundations(doc, fonts, data));
  allPages.push(buildPage4_ReputationDiscoverabilityEmail(doc, fonts, data));

  // Page 5 may return multiple pages
  const breakdownPages = buildPage5_ScoreBreakdown(doc, fonts, data);
  allPages.push(...breakdownPages);

  // Add page footers with correct total
  const totalPages = allPages.length;
  for (let i = 0; i < totalPages; i++) {
    drawPageFooter(allPages[i], fonts, i + 1, totalPages);
  }

  return doc.save();
}
